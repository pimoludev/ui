
import {
  readdir,
  readFile,
  writeFile,
  mkdir,
} from "node:fs/promises";

import { validateVisual } from "./validate-visuals.mjs";

const inputDir = new URL("../src/visual/", import.meta.url);
const outputDir = new URL("../dist/", import.meta.url);

const files = (await readdir(inputDir))
  .filter((file) => file.endsWith(".json"))
  .sort();

if (files.length === 0) {
  throw new Error("No Pimolu visual presets found.");
}

/* Keys are the exact CSS variable suffix: no name transformation. */
const toCSSVariable = (key) => `--pimolu-${key}`;

function toDeclarations(tokens, indent = "  ") {
  return Object.entries(tokens)
    .map(
      ([key, value]) =>
        `${indent}${toCSSVariable(key)}: ${value};`
    )
    .join("\n");
}

const data = {};
let css = "/* Generated by Pimolu UI — do not edit */\n\n";

for (const file of files) {
  const name = file.replace(/\.json$/, "");

  if (!/^[a-z][a-z0-9-]*$/.test(name)) {
    throw new Error(`Invalid visual preset name: ${name}`);
  }

  const source = JSON.parse(
    await readFile(new URL(file, inputDir), "utf8")
  );

  validateVisual(name, source);

  data[name] = source;

  css += `[data-pimolu-style="${name}"] {\n`;
  css += toDeclarations(source.light);
  css += "\n}\n\n";

  if (Object.keys(source.dark).length > 0) {
    css += `[data-pimolu-theme="dark"][data-pimolu-style="${name}"] {\n`;
    css += toDeclarations(source.dark);
    css += "\n}\n\n";

    css += "@media (prefers-color-scheme: dark) {\n";
    css += `  [data-pimolu-theme="system"][data-pimolu-style="${name}"] {\n`;
    css += toDeclarations(source.dark, "    ");
    css += "\n  }\n}\n\n";
  }
}

const names = Object.keys(data);

const js = `/* Generated by Pimolu UI */
export const pimoluPresetVisuals = ${JSON.stringify(data, null, 2)};
`;

const types = [
  'export type PimoluVisualTheme = "light" | "dark";',

  `export type PimoluVisualStylePreset = ${names
    .map((name) => JSON.stringify(name))
    .join(" | ")};`,

  "export type PimoluVisualTokens = Readonly<Record<string, string>>;",

  "export declare const pimoluPresetVisuals: Readonly<Record<PimoluVisualStylePreset, Record<PimoluVisualTheme, PimoluVisualTokens>>>;",

  "",
].join("\n");

await mkdir(outputDir, { recursive: true });

await Promise.all([
  writeFile(new URL("visual.css", outputDir), css, "utf8"),
  writeFile(new URL("visuals.js", outputDir), js, "utf8"),
  writeFile(new URL("visuals.d.ts", outputDir), types, "utf8"),
]);

console.log(
  `Generated CSS and JavaScript for ${names.length} Pimolu visual presets.`
);
