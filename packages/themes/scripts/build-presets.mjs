
import {
  readdir,
  readFile,
  writeFile,
  mkdir,
} from "node:fs/promises";
import { validatePreset } from "./validate-presets.mjs";

const inputDir = new URL("../src/presets/", import.meta.url);
const outputDir = new URL("../dist/", import.meta.url);
const outputFile = new URL("presets.css", outputDir);

// Read all preset JSON files
const files = (await readdir(inputDir))
  .filter((file) => file.endsWith(".json"))
  .sort();

if (files.length === 0) {
  throw new Error("No Pimolu presets found.");
}

// Convert camelCase to CSS variables
function toCSSVariables(tokens) {
  return Object.entries(tokens)
    .map(([key, value]) => {
      if (typeof value !== "string") {
        throw new Error(`Invalid token: ${key}`);
      }

      const name = key.replace(
        /[A-Z]/g,
        (letter) => `-${letter.toLowerCase()}`
      );

      return `  --pimolu-${name}: ${value};`;
    })
    .join("\n");
}


const presetData = {};


let css = "/* Generated by Pimolu UI — Do not edit */\n\n";

for (const file of files) {
  const preset = file.replace(/\.json$/, "");

  if (!/^[a-z][a-z0-9-]*$/.test(preset)) {
    throw new Error(`Invalid preset name: ${preset}`);
  }

  const source = JSON.parse(
    await readFile(new URL(file, inputDir), "utf8")
  );

  validatePreset(preset, source);

  for (const mode of ["light", "dark"]) {
    if (!source[mode] || typeof source[mode] !== "object") {
      throw new Error(`Missing ${mode} tokens in ${file}`);
    }
    
    presetData[preset] = source;


    const selector =
      mode === "light"
        ? `[data-pimolu-style="${preset}"]`
        : `[data-pimolu-theme="dark"][data-pimolu-style="${preset}"]`;

    css += `${selector} {\n`;
    css += toCSSVariables(source[mode]);
    css += "\n}\n\n";
  }

  
  // System mode: use dark palette when the OS prefers dark

  const systemSelector = `[data-pimolu-theme="system"][data-pimolu-style="${preset}"]`;

  const systemDarkVariables = toCSSVariables(source.dark)
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");

  css += `@media (prefers-color-scheme: dark) {
    ${systemSelector} {
      ${systemDarkVariables}
    }
  }

  `;

}



const names = Object.keys(presetData);

// JavaScript output
const js = `/* Generated by Pimolu UI */
export const pimoluPresets = ${JSON.stringify(presetData, null, 2)};
`;

// TypeScript declarations
const types = [
  'export type PimoluTheme = "light" | "dark";',

  `export type PimoluStylePreset = "default" | ${names
    .map((name) => JSON.stringify(name))
    .join(" | ")};`,

  'export type PimoluPresetColors = Readonly<Record<string, string>>;',

  'export declare const pimoluPresets: Readonly<Record<Exclude<PimoluStylePreset, "default">, Record<PimoluTheme, PimoluPresetColors>>>;',
  "",
].join("\n");

// Write generated files
await mkdir(outputDir, { recursive: true });

await Promise.all([
  writeFile(outputFile, css, "utf8"),

  writeFile(
    new URL("presets.js", outputDir),
    js,
    "utf8"
  ),

  writeFile(
    new URL("presets.d.ts", outputDir),
    types,
    "utf8"
  ),
]);

console.log(
  `Generated CSS and JavaScript for ${names.length} Pimolu presets.`
);
