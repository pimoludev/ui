
import { readFile, writeFile } from "node:fs/promises";

const input = new URL("../dist/themes.json", import.meta.url);
const output = new URL("../dist/default.css", import.meta.url);

const themes = JSON.parse(await readFile(input, "utf8"));

function toVariables(tokens) {
  if (!tokens || typeof tokens !== "object" || Array.isArray(tokens)) {
    throw new Error("Invalid default theme tokens");
  }

  return Object.entries(tokens)
    .map(([name, value]) => {
      if (
        !/^[a-z][a-z0-9-]*$/.test(name) ||
        typeof value !== "string" ||
        /[;{}]/.test(value)
      ) {
        throw new Error(`Invalid token: ${name}`);
      }

      return `  --pimolu-${name}: ${value};`;
    })
    .join("\n");
}

function createRule(selector, tokens) {
  return `${selector} {\n${toVariables(tokens)}\n}\n\n`;
}

const light = themes.light;
const dark = themes.dark;

if (!light || !dark) {
  throw new Error("Default light/dark themes are required");
}

let css = "/* Generated by Pimolu UI */\n\n";

// Explicit modes
for (const mode of ["light", "dark"]) {
  css += createRule(
    `[data-pimolu-theme="${mode}"][data-pimolu-style="default"]`,
    themes[mode]
  );
}

// System: light as baseline
css += createRule(
  '[data-pimolu-theme="system"][data-pimolu-style="default"]',
  light
);

// System: dark according to the browser
css += "@media (prefers-color-scheme: dark) {\n";

css += createRule(
  '  [data-pimolu-theme="system"][data-pimolu-style="default"]',
  dark
);

css += "}\n";

await writeFile(output, css, "utf8");

console.log("Generated Pimolu Default with system theme support.");
